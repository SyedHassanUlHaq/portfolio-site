import { site } from "../../content/site";

export const baseUrl = site.url.replace(/\/$/, "");
export const abs = (path: string) => `${baseUrl}${path}`;

/** Keeps the page title within ~60 characters: appends the site name only when it fits. */
export function pageTitle(title: string): string {
  const full = `${title} | ${site.name}`;
  return full.length <= 60 ? full : title;
}

/** Trims a description to 160 characters at a word boundary; pads very short ones so snippets aren't thin. */
export function metaDescription(text: string): string {
  let t = text.trim();
  if (t.length < 110) t = `${t} Built by ${site.name}.`;
  if (t.length <= 160) return t;
  const cut = t.slice(0, 157);
  return `${cut.slice(0, cut.lastIndexOf(" "))}…`;
}

/** 1200x630 social-preview image (generated by `npm run thumbnails`). */
export const ogImageUrl = (slug: string) => abs(`/projects/${slug}/thumbnail-og.jpg`);
export const homeOgImageUrl = abs("/images/og-home.jpg");

export const crumbs = (items: { name: string; path: string }[]) => ({
  "@type": "BreadcrumbList",
  itemListElement: items.map((c, i) => ({ "@type": "ListItem", position: i + 1, name: c.name, item: abs(c.path) })),
});
